-- 1. Tabla principal `registros` (Bitácora de Parcela)
CREATE TABLE IF NOT EXISTS public.registros (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fecha date NOT NULL DEFAULT CURRENT_DATE,
  parcela text NOT NULL,
  cultivo text NOT NULL,
  actividad text NOT NULL,
  observaciones text,
  pct numeric,
  semaforo text DEFAULT 'amarillo',
  prioridad integer DEFAULT 0,
  tecnico_id text,
  creado timestamptz NOT NULL DEFAULT now()
);

-- Si la tabla `registros` ya había sido creada solo con las 7 columnas básicas,
-- agregamos de forma segura las columnas opcionales de clasificación:
ALTER TABLE public.registros ADD COLUMN IF NOT EXISTS pct numeric;
ALTER TABLE public.registros ADD COLUMN IF NOT EXISTS semaforo text DEFAULT 'amarillo';
ALTER TABLE public.registros ADD COLUMN IF NOT EXISTS prioridad integer DEFAULT 0;
ALTER TABLE public.registros ADD COLUMN IF NOT EXISTS tecnico_id text;
ALTER TABLE public.registros ADD COLUMN IF NOT EXISTS creado timestamptz NOT NULL DEFAULT now();

CREATE INDEX IF NOT EXISTS idx_registros_fecha ON public.registros (fecha DESC, id DESC);

-- 2. Tabla `casos` (Casos fitosanitarios del Hackathon Alerta Plaga — Nivel 1 y 2)
CREATE TABLE IF NOT EXISTS public.casos (
  reporte_id text PRIMARY KEY,
  recibido timestamptz,
  parcela_id text,
  productor_id text,
  cultivo text,
  plaga text NOT NULL,
  semaforo text,
  prioridad integer,
  tecnico_id text,
  brote boolean NOT NULL DEFAULT false,
  lat double precision,
  lon double precision,
  pct numeric,
  es_plaga boolean NOT NULL DEFAULT true,
  origen text DEFAULT 'agente',
  creado timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_casos_recibido ON public.casos (recibido DESC);
CREATE INDEX IF NOT EXISTS idx_casos_semaforo ON public.casos (semaforo);
CREATE INDEX IF NOT EXISTS idx_casos_plaga ON public.casos (plaga);

-- 3. Tabla `avisos` (Buzón Oficial de Avisos: folio, asignacion, cuarentenaria, brote)
CREATE TABLE IF NOT EXISTS public.avisos (
  id text PRIMARY KEY,
  reporte_id text,
  equipo_id text,
  tipo text NOT NULL,
  para jsonb NOT NULL DEFAULT '[]'::jsonb,
  mensaje text NOT NULL,
  creado timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_avisos_creado ON public.avisos (creado DESC);
CREATE INDEX IF NOT EXISTS idx_avisos_reporte_id ON public.avisos (reporte_id);

-- 4. Vista analítica `vista_resumen_casos`
CREATE OR REPLACE VIEW public.vista_resumen_casos AS
SELECT
  semaforo,
  plaga,
  brote,
  COUNT(*) AS total_casos,
  ROUND(AVG(prioridad), 1) AS prioridad_promedio,
  COUNT(DISTINCT parcela_id) AS parcelas_afectadas,
  COUNT(DISTINCT tecnico_id) AS tecnicos_asignados
FROM public.casos
WHERE es_plaga = true
GROUP BY semaforo, plaga, brote
ORDER BY total_casos DESC;

